// The components of blockr.ui, which a module imports as `@blockr/ui`,
// and which the page's import map resolves to blockr-ui.js (./import-map/index.ts).
// They are React Aria's, drawn with the theme variables after React Aria's Tailwind starter kit,
// and moved from core's React SDK with their names and their props, so that a UI that draws with one
// changes only its import, from `@blockr/core/react` to `@blockr/ui`
// (https://github.com/BristolMyersSquibb/blockr/wiki/Rewrite-1.7.3#the-first-set).
// The one exception is `Stack`, which lays out the controls of a UI one below the other,
// and which is `FormLayout` here, since a stack is a group of blocks in blockr.
// They are the inputs, each of which takes the value that it shows and submits through its prop `bound`,
// of the interface `Bound`, and the buttons, the overlays, the layout, the table, the trees and the grid list,
// with what drags the items of the last three and drops onto them.
// Beside them are the parts of React Aria that core's React SDK exported as they are,
// such as `Autocomplete`, `Text` and `Focusable`, and `Icon` and `iconMarkup()`,
// which draw an icon of Lucide's from @blockr/ui/icons.
// Later, blockr.ui added `Label`, `Description` and `FieldError`, the parts that draw the label,
// the description and the error of a field, after the starter kit.

